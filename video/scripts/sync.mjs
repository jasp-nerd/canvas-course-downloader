// Copies the extension's fonts and Pip into assets/, and writes the logo's real geometry as
// assets/logo.js, so the films use the same files as the product (the copies are gitignored).
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { LOGO_ARROW, LOGO_DOTS, LOGO_TRANSFORM, LOGO_VIEWBOX } from '../../src/ui/logo-paths.ts';

for (const dir of ['fonts', 'pip']) {
  mkdirSync(`assets/${dir}`, { recursive: true });
  cpSync(`../public/${dir}`, `assets/${dir}`, { recursive: true });
}
writeFileSync(
  'assets/logo.js',
  `// Generated by scripts/sync.mjs from src/ui/logo-paths.ts.\nwindow.LOGO = ${JSON.stringify({ viewBox: LOGO_VIEWBOX, transform: LOGO_TRANSFORM, dots: LOGO_DOTS, arrow: LOGO_ARROW })};\n`,
);

// Our own UI sounds, made from sine waves and noise, so there's no licence to track.
mkdirSync('assets/sfx', { recursive: true });
const sounds = {
  // A short, soft click: filtered noise with a fast decay.
  'click.wav': ['-f', 'lavfi', '-i', 'anoisesrc=d=0.06:c=pink:a=0.6', '-af', 'highpass=f=900,lowpass=f=5000,afade=t=out:st=0:d=0.06,volume=0.9'],
  // A two-note chime for "saved": E6 then A6, each fading out.
  'chime.wav': ['-f', 'lavfi', '-i', 'sine=f=1318.5:d=1.2', '-f', 'lavfi', '-i', 'sine=f=1760:d=1.2', '-filter_complex', '[0]afade=t=out:st=0:d=1.1,volume=0.22[a];[1]adelay=110|110,afade=t=out:st=0.1:d=1.1,volume=0.18[b];[a][b]amix=inputs=2:normalize=0'],
  // A lighter, higher click for ticking a checkbox.
  'tick.wav': ['-f', 'lavfi', '-i', 'anoisesrc=d=0.035:c=pink:a=0.5', '-af', 'highpass=f=2500,lowpass=f=8000,afade=t=out:st=0:d=0.035,volume=0.7'],
  // A soft pop for Pip: a short sine sweep.
  'pop.wav': ['-f', 'lavfi', '-i', 'sine=f=520:d=0.12', '-af', 'vibrato=f=18:d=0.4,afade=t=out:st=0.02:d=0.1,volume=0.5'],
};
for (const [name, args] of Object.entries(sounds)) {
  if (!existsSync(`assets/sfx/${name}`)) execFileSync('ffmpeg', ['-loglevel', 'error', ...args, '-ar', '48000', `assets/sfx/${name}`]);
}
